package convert

import (
	"bytes"
	"testing"
)

func TestSniffDeclared_PNG(t *testing.T) {
	png := []byte{
		0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,
		0x00, 0x00, 0x00, 0x0D,
		0x49, 0x48, 0x44, 0x52,
		0x00, 0x00, 0x00, 0x64,
		0x00, 0x00, 0x00, 0x64,
	}
	got, err := SniffDeclared(bytes.NewReader(png), int64(len(png)), "png", OperationConvert, 500<<20)
	if err != nil {
		t.Fatal(err)
	}
	if got != "png" {
		t.Fatalf("detected %q", got)
	}
}
